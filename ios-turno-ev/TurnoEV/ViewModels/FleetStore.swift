            at: 0
        )
        persist()
    }

    // MARK: - Persistence

    private func apply(_ state: PersistedState) {
        session = state.session
        enrolledAccountId = state.enrolledAccountId
        vehicles = state.vehicles
        activeShift = state.activeShift
        history = state.history
        incomes = state.incomes
        incidents = state.incidents
        notices = state.notices
        credit = state.credit
        clockOffsetMinutes = state.clockOffsetMinutes
        supervisorReports = state.supervisorReports
        recoveryBookings = state.recoveryBookings
        notifiedBonusWeeks = state.notifiedBonusWeeks
    }

    private func persist() {
        let state = PersistedState(
            session: session,
            enrolledAccountId: enrolledAccountId,
            vehicles: vehicles,
            activeShift: activeShift,
            history: history,
            incomes: incomes,
            incidents: incidents,
            notices: notices,
            credit: credit,
            clockOffsetMinutes: clockOffsetMinutes,
            supervisorReports: supervisorReports,
            recoveryBookings: recoveryBookings,
            notifiedBonusWeeks: notifiedBonusWeeks
        )
        do {
            let encoder = JSONEncoder()
            encoder.dateEncodingStrategy = .iso8601
            let data = try encoder.encode(state)
            UserDefaults.standard.set(data, forKey: Self.storageKey)
        } catch {
            print("No se pudo guardar el estado local: \(error.localizedDescription)")
        }
    }

    nonisolated private static func restore() -> PersistedState? {
        guard let data = UserDefaults.standard.data(forKey: storageKey) else { return nil }
        do {
            let decoder = JSONDecoder()
            decoder.dateDecodingStrategy = .iso8601
            return try decoder.decode(PersistedState.self, from: data)
        } catch {
            print("No se pudo leer el estado local: \(error.localizedDescription)")
            return nil
        }
    }
