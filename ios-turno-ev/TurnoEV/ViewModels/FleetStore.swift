    /// Loads the operational state that belongs to one backend identity, and only that.
    ///
    /// Two independent guarantees, on purpose. The storage key already separates one
    /// driver from another, and on top of it every record is checked against the
    /// `driverId` it carries. A driver who has never worked — no stored state at all —
    /// lands on a genuinely empty operation: no shift, no history, no income, no incident,
    /// no credit, no unit.
    ///
    /// `enrolledAccountId` and `clockOffsetMinutes` are deliberately left alone: the
    /// biometric link and the simulation clock belong to the device, not to the driver.
    private func adoptIdentityState(profileId: String) {
        // The capability of the environment the state is being read **for**. Taken from
        // `adoptedEnvironment` rather than from `operationalCapability` because this runs
        // mid-swap, before the session is necessarily standing: inside the laboratory a
        // proved identity keeps its simulated cycle, in production it keeps none of it.
        let capability: OperationalCapability = adoptedEnvironment == .production
            ? .stationRequired
            : .localWorkflow
        // Resolved from the same environment, separately on purpose: the two boundaries
        // answer alike today and are expected to diverge — a station can start publishing
        // notices long before it can certify a shift.
        let authority: NoticeAuthority = adoptedEnvironment == .production
            ? .stationPublished
            : .localBulletin
        let owned = Self.ownedState(
            Self.restore(
                key: Self.identityStorageKey(profileId: profileId, environment: adoptedEnvironment),
                defaults: defaults
            ),
            driverId: profileId,
            capability: capability,
            noticeAuthority: authority
        )
        vehicles = owned.vehicles
        activeShift = owned.activeShift
        history = owned.history
        incomes = owned.incomes
        incidents = owned.incidents
        notices = owned.notices
        credit = owned.credit
        supervisorReports = owned.supervisorReports
        recoveryBookings = owned.recoveryBookings
        notifiedBonusWeeks = owned.notifiedBonusWeeks
        // Resolved again from the assignment book, which is keyed by driver.
        unitAssignment = nil
    }

    /// Brings the demonstration state back into memory when a backend session ends.
    ///
    /// Without this the empty operation of the backend driver would be the thing standing
    /// in memory when the next `persist()` writes to the demonstration key — which would
    /// erase the demo data instead of isolating it.
    private func adoptDemoState() {
        driver = MockData.driver
        if let stored = Self.restore(key: Self.demoStorageKey, defaults: defaults) {
            enrolledAccountId = stored.enrolledAccountId
            applyOperational(stored)
        } else {
            seedDemoState()
        }
        unitAssignment = nil
    }

    /// Closes the session and returns to the access screen. The automatic scan is held
    /// back so another role can be identified instead of re-entering the same one.
    func signOut() {
        let wasBackendSession = isBackendSession
        // Saved under the key of the identity that is leaving, before it stops being the
        // current one.
        persist()
        session = nil
        awaitsCredentialChoice = true
        if wasBackendSession {
            adoptDemoState()
            reloadAssignment()
        }
        persist()
    }

    /// Removes the biometric link so the next access requires full credentials.
    func forgetDevice() {
        let wasBackendSession = isBackendSession
        persist()
        enrolledAccountId = nil
        session = nil
        awaitsCredentialChoice = true
        if wasBackendSession {
            adoptDemoState()
            enrolledAccountId = nil
            reloadAssignment()
        }
        persist()
    }

    /// Rebuilds the operational state from the active environment. Called whenever the
    /// laboratory changes the world so every interface reflects it immediately.
    func adoptEnvironment() {
        defer { reloadAssignment() }

        // The switch itself, and the only place it happens.
        //
        // A proved identity keeps its session, its credentials and its driver profile
        // across this: the environment changes underneath the same person. What is
        // exchanged is the operational blob — written under the key of the environment
        // being left, read from the key of the one being entered. Nothing is deleted on
        // either side, so the way out of the laboratory costs the real operation nothing,
        // and the way in costs the experiment nothing.
        let previous = adoptedEnvironment
        let current = environmentSource.mode
        if previous != current {
            persist(key: storageKey(for: previous))
            adoptedEnvironment = current
            if let profileId = session?.principal?.profileId {
                adoptIdentityState(profileId: profileId)
            }
        }

        // Same reasoning as in `init`: the session outlives the environment switch, so the
        // profile is resolved from the credential and only falls back to the
        // environment's default driver when the credential has none.
        //
        // A backend session is exempt: its driver was proved by the server and no
        // environment switch may replace that person with a seeded or laboratory one.
        if session?.principal == nil {
            driver = MockData.driver
            adoptSessionDriver()
        }
        // The environment is a **demonstration** world: switching it may not hand its
        // catalogue to an identity the server never sent one to. This was the documented
        // contradiction — with an empty inventory every unit fell through to `incoming`
        // and the whole demo fleet landed on a proved driver.
        let source = UnitAssignmentRules.catalogue(MockData.vehicles, capability: unitAssignmentCapability)
        let activeVehicleId = activeShift?.vehicleId

        vehicles = source.map { incoming in
            guard let kept = vehicles.first(where: { $0.id == incoming.id }) else { return incoming }
            // A unit inside a running shift keeps its live readings; every other unit
            // follows the environment, so lab edits land immediately.
            guard kept.id != activeVehicleId, LabRuntime.isTest else { return kept }
            return incoming
        }

        if let shift = activeShift, !vehicles.contains(where: { $0.id == shift.vehicleId }) {
            activeShift = nil
        }
        persist()
    }

    /// Wipes every operational record of the driver interface, leaving it at zero.
    ///
    /// "At zero" means different things per session, and both are literal. A
    /// demonstration one is rebuilt on the seeded catalogue so the world stays walkable;
    /// a proved identity is left with no inventory at all, because a wipe that ends with
    /// a fleet the station never sent is not a wipe.
    func clearOperationalData() {
        let capability = unitAssignmentCapability
        vehicles = UnitAssignmentRules.catalogue(MockData.vehicles, capability: capability)
        activeShift = nil
        history = []
        incomes = []
        incidents = []
        notices = []
        credit = nil
        supervisorReports = []
        recoveryBookings = []
        notifiedBonusWeeks = []
        clockOffsetMinutes = 0
        // The book is shared by the whole device and a proved identity owns no row in it.
        // Wiping it from here would erase the station's demonstration assignments — other
        // people's records — as a side effect of clearing this driver's own operation.
        if capability.allowsLocalSimulation {
            driver = MockData.driver
            AssignmentBook.clear()
        }
        unitAssignment = nil
        persist()
    }

