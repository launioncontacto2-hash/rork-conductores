    func resetDemoData() {
        guard !LabRuntime.isTest else {
            clearOperationalData()
            return
        }
        let seedDate = Date()
        let seedHistory = MockData.shiftHistory(driver: driver, now: seedDate)
        vehicles = MockData.syncOdometers(vehicles: MockData.vehicles, history: seedHistory)
        history = seedHistory
        incomes = MockData.incomeHistory(driver: driver, history: seedHistory)
        incidents = MockData.incidents(driver: driver, now: seedDate)
        notices = MockData.notices(now: seedDate)
        credit = MockData.credit(now: seedDate)
        supervisorReports = MockData.supervisorReports(now: seedDate)
        recoveryBookings = []
        notifiedBonusWeeks = []
        activeShift = nil
        clockOffsetMinutes = 0
        CashDepositLedger.clear()
        CashChargeLedger.clear()
        persist()
    }

    // MARK: - Bonuses

    private func bonusInput(reference: Date) -> BonusRules.EvaluationInput {
        BonusRules.EvaluationInput(
            driver: driver,
            goals: goals,
            history: history,
            incomes: incomes,
            reports: supervisorReports,
            schedule: NationalBonusBoard.current,
            now: reference
        )
    }

    func bonusEvaluations(reference: Date) -> [BonusEvaluation] {
        BonusRules.evaluateAll(bonusInput(reference: reference))
    }

    /// Money still collectable at month end with the current weekly evaluation.
    func bonusPayableMxn(reference: Date) -> Int {
        bonusEvaluations(reference: reference).reduce(0) { $0 + $1.payableMxn }
    }

    /// Everything the month can pay with the amounts the national administration has
    /// in force. Stations cannot alter this number.
    func bonusTotalMxn() -> Int {
        NationalBonusBoard.current.ceilingMxn
    }

    /// Raises the popup for the first closed week that broke a bonus, once only.
    @discardableResult
    func raiseBonusAlert(reference: Date) -> BonusAlert? {
        let evaluations = bonusEvaluations(reference: reference)
        for evaluation in evaluations {
            for result in evaluation.weeks where result.status == .lost {
                let id = "\(evaluation.kind.rawValue)-\(Fmt.monthKey(reference))-\(result.week.index)"
                guard !notifiedBonusWeeks.contains(id) else { continue }
                let message = "¡\(Fmt.firstName(driver.name)) has perdido el bono de \(evaluation.kind.shortName)! Agenda hoy tu lugar en el programa de recuperación de bonos"
                notifiedBonusWeeks.append(id)
                pushNotice(
                    kind: .reminder,
                    title: message,
                    body: "Semana \(result.week.index) (\(result.week.rangeLabel)): \(result.detail)."
                )
                return BonusAlert(id: id, kind: evaluation.kind, weekIndex: result.week.index, message: message)
            }
        }
        return nil
    }

    // MARK: - Recovery program

    func recoveryBooking(on day: Date) -> RecoveryBooking? {
        recoveryBookings.first { ShiftRules.isSameDay($0.date, day) }
    }

    var upcomingRecoveryBookings: [RecoveryBooking] {
        recoveryBookings.sorted { $0.date < $1.date }
    }

    @discardableResult
    func bookRecovery(date: Date, slot: ShiftSlot, bonus: BonusKind) -> Bool {
        guard BonusRules.canBook(driver: driver, date: date, now: now) else { return false }
        guard recoveryBooking(on: date) == nil else { return false }

        let booking = RecoveryBooking(
            id: "rec-\(UUID().uuidString.prefix(8))",
            date: ShiftRules.calendar.startOfDay(for: date),
            slot: slot,
            bonus: bonus,
            createdAt: now
        )
        recoveryBookings.append(booking)
        pushNotice(
            kind: .station,
            title: "Reserva confirmada en recuperación de bonos",
            body: "\(Fmt.dateShort(booking.date).capitalized) · turno \(slot.label.lowercased()) \(slot.rangeLabel). Recuperas el bono de \(bonus.shortName)."
        )
        return true
    }

    func cancelRecovery(id: String) {
        recoveryBookings.removeAll { $0.id == id }
        persist()
    }

