        CashChargeLedger.add(charge)
        pushNotice(
            kind: .station,
            title: "Viaje cobrado en efectivo",
            body: "\(charge.tripReference) por \(Fmt.mxn(amountMxn)). Deposítalo hoy antes de las 23:59:59 o se descontará de tus ingresos de la semana."
        )
        return charge
    }

    /// Closes every cash charge whose day already ended without a deposit. From here the
    /// amount stops being a pending deposit and becomes a discount on the week, visible
    /// in the wallet as "Cobro de viaje en efectivo".
    ///
    /// The list it works from is already scoped to this session's ledger, and the test is
    /// repeated below anyway: this is the exact step where a charge stops being a pending
    /// deposit and becomes money taken off a week, and a fixture must never be able to
    /// make that crossing inside a real identity's book.
    @discardableResult
    func chargeBackExpiredCashCharges() -> [CashCharge] {
        let ledger = ledgerOrigin
        let expired = openCashCharges.filter {
            $0.origin == ledger && now > CashChargeRules.deadline(for: $0)
        }
        guard !expired.isEmpty else { return [] }

        for charge in expired {
            CashChargeLedger.markChargedBack(id: charge.id, at: now)
            pushNotice(
                kind: .credit,
                title: "\(CashChargeRules.recoveryConcept) · \(Fmt.mxn(charge.amountMxn))",
                body: "El viaje \(charge.tripReference) del \(Fmt.dateShort(charge.generatedAt)) no se depositó el mismo día. El monto se descuenta de tus ingresos al cierre de la semana."
            )
        }
        return expired
    }

    /// Files a cash deposit: the income enters the day, the slip stays attached and the
    /// manager of the station is notified in the same movement. Cash is not an authorized
    /// way to charge, so every peso received in hand has to leave a trace.
    ///
    /// Throws under a proved identity, before anything is written. Filing a deposit is
    /// the app asserting that money reached the network's account; done locally that is a
    /// receipt for a transfer nobody made, against a bank account no authority published.
    @discardableResult
    func registerCashDeposit(
        charge: CashCharge,
        declaredMxn: Int,
        detectedMxn: Int?,
        match: DepositMatch,
        accountMatch: DepositMatch,
        detectedAccount: String?,
        slip: Data?
    ) throws -> CashDeposit {
        guard canSimulateFinancialState, let account = cashDepositAccount else {
            throw FinancialMutationError.backendRequired
        }

        let deposit = CashDeposit(
            id: "dep-\(UUID().uuidString.prefix(8))",
            origin: ledgerOrigin,
            stationId: driver.stationId,
            driverId: driver.id,
            driverName: driver.name,
            vehicleNumber: displayVehicle?.internalNumber ?? "Sin unidad",
            declaredMxn: declaredMxn,
            detectedMxn: detectedMxn,
            match: match,
            accountMatch: accountMatch,
            detectedAccount: detectedAccount,
            bank: account.bank,
            clabe: account.clabe,
            createdAt: now,
            slip: slip,
            acknowledgedAt: nil
        )
        CashDepositLedger.record(deposit)
        CashChargeLedger.markDeposited(id: charge.id, at: now)

        // The guard above is the boundary now, so this is reached only inside a session
        // that may simulate. The call stays unconditional to keep the deposit and the
        // income it books inseparable: a slip filed without its matching entry would be
        // money that left the driver's hands and never appeared in the week.
        appendIncome(
            amountMxn: declaredMxn,
            trips: 0,
            platform: .cash,
            evidence: slip,
            note: "\(charge.tripReference) · depósito en \(account.bank)"
        )

        pushNotice(
            kind: .station,
            title: "Depósito en efectivo notificado a gerencia",
            body: "\(Fmt.mxn(declaredMxn)) del viaje \(charge.tripReference) depositados en \(account.bank). El gerente de \(driver.station) recibió el comprobante."
        )
        return deposit
    }

    /// Files an incident report.
    ///
    /// Throws under a proved identity in production, before the record exists. The
    /// notice this raises says "Incidencia enviada a la estación" and the row lands as
    /// `.open`, which every screen renders as *waiting for supervision*. There is no
    /// supervision service behind it: after a collision with a third party, a driver who
    /// believes the station was notified and is waiting is in a materially worse position
    /// than one who knows they still have to call.
    ///
    /// The screen stays open and the photographs stay capturable — as a draft the caller
    /// holds, never as `incidents`, which is the list that means "reported".
    func reportIncident(kind: IncidentKind, description: String, photos: [Data]) throws {
        guard canRunOperationalCycle else { throw OperationalMutationError.backendRequired }
        let vehicle = activeVehicle ?? vehicles.first
        let incident = Incident(
            id: "inci-\(UUID().uuidString.prefix(8))",
            driverId: driver.id,
            vehicleId: vehicle?.id ?? "—",
            vehicleInternalNumber: vehicle?.internalNumber ?? "—",
            kind: kind,
            createdAt: now,
            description: description,
            photos: photos,
            status: .open,
            origin: operationalOrigin
        )
        incidents.insert(incident, at: 0)
        pushNotice(
            kind: .station,
            title: "Incidencia enviada a la estación",
            body: "Tu reporte de \(kind.label.lowercased()) quedó en revisión."
        )
        persist()
    }

    /// Closes the open shift: files the record, releases the unit and returns the summary.
    ///
    /// Two refusals, and they are different questions. The first is the boundary: closing
    /// a shift writes the row a settlement multiplies and four bonuses are judged on, and
    /// there is no station to certify it. The second is about the shift itself — a
    /// `.simulated` one left open in the laboratory cannot be closed from production, or
    /// the exit from a simulation would mint a real closed shift out of it. Neither
    /// deletes anything: the simulated shift stays in its own container, closeable where
    /// it was opened.
    func finishShift(endOdometerKm: Int, endBatteryPct: Int, photo: Data?) throws -> ShiftSummary {
        guard canRunOperationalCycle else { throw OperationalMutationError.backendRequired }
        guard let shift = activeShift else {
            return ShiftSummary(
                kmDriven: 0,
                durationMinutes: 0,
                earningsMxn: 0,
                trips: 0,
                dailyGoalMxn: goals.dailyMxn,
                missingMxn: goals.dailyMxn,
                missingTrips: goals.tripsPerDay,
                lateMinutes: 0
            )
        }
        guard canActOnActiveShift else { throw OperationalMutationError.unauthoritativeShift }

        let endedAt = now
        let record = ShiftRecord(
            id: shift.id,
            driverId: shift.driverId,
            vehicleId: shift.vehicleId,
            vehicleInternalNumber: activeVehicle?.internalNumber ?? "—",
            group: shift.group,
            slot: shift.slot,
            scheduledStartAt: shift.scheduledStartAt,
            startedAt: shift.startedAt,
            endedAt: endedAt,
            lateMinutes: shift.lateMinutes,
            paidBackMinutes: 0,
            startOdometerKm: shift.startOdometerKm,
            endOdometerKm: endOdometerKm,
            startBatteryPct: shift.startBatteryPct,
            endBatteryPct: endBatteryPct,
            trips: shift.trips,
            earningsMxn: shift.earningsMxn,
            // Inherited from the shift, never recomputed from the current session: a
            // block opened inside a simulation stays a simulated block once closed.
            origin: shift.origin
        )

        history.insert(record, at: 0)
        if let index = vehicles.firstIndex(where: { $0.id == shift.vehicleId }) {
            vehicles[index].status = .available
            vehicles[index].occupiedBy = nil
            vehicles[index].odometerKm = endOdometerKm
            vehicles[index].batteryPct = endBatteryPct
        }
        if photo != nil {
            // Final odometer evidence is archived with the closed shift record.
            pushNotice(
                kind: .station,
                title: "Turno cerrado",
                body: "Entregaste \(record.vehicleInternalNumber) con \(Fmt.km(endOdometerKm)). Duración \(Fmt.durationText(record.durationMinutes))."
            )
        }
        activeShift = nil
        persist()

        return ShiftSummary(
            kmDriven: record.kmDriven,
            durationMinutes: record.durationMinutes,
            earningsMxn: record.earningsMxn,
            trips: record.trips,
            dailyGoalMxn: goals.dailyMxn,
            missingMxn: max(0, goals.dailyMxn - record.earningsMxn),
            missingTrips: max(0, goals.tripsPerDay - record.trips),
            lateMinutes: record.lateMinutes
        )
    }

    /// Applies paid-back minutes to the oldest pending late day of the current week.
    @discardableResult
    func payLateTime(minutes: Int) -> Int {
        var remaining = minutes
        var applied = 0
        let weekDays = weeklyLateBreakdown(reference: now).filter { $0.pendingMinutes > 0 }
        let pendingDates = weekDays.map(\.date)

        for index in history.indices where remaining > 0 {
            let record = history[index]
            guard pendingDates.contains(where: { ShiftRules.isSameDay($0, record.startedAt) }) else { continue }
            let pending = record.pendingLateMinutes
            guard pending > 0 else { continue }
            let pay = min(pending, remaining)
            history[index].paidBackMinutes += pay
            remaining -= pay
            applied += pay
        }

        if applied > 0 { persist() }
        return applied
    }

