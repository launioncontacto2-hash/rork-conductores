import Foundation
import Observation

/// Single source of truth for the driver session, the active shift and every log.
/// Persists to `UserDefaults` so a reopened app keeps the shift running.
@Observable
final class FleetStore {
    // MARK: - Persisted shape

    nonisolated private struct PersistedState: Codable, Sendable {
        var session: StaffSession?
        /// Account linked to this device; only it can unlock with Face ID.
        var enrolledAccountId: String?
        var vehicles: [Vehicle]
        var activeShift: ActiveShift?
        var history: [ShiftRecord]
        var incomes: [IncomeEntry]
        var incidents: [Incident]
        var notices: [Notice]
        var credit: CreditAccount?
        var clockOffsetMinutes: Int
        var supervisorReports: [SupervisorReport]
        var recoveryBookings: [RecoveryBooking]
        var notifiedBonusWeeks: [String]
    }

    private static let storageKey = "turnoev.state.v4"

    /// Average fleet speed used to estimate distance until real GPS/telemetry lands.
    private static let simulatedKmPerMinute = 0.32

    // MARK: - State

    /// Driver profile of the open session. It follows the active environment: seeded in
    /// production, created by the laboratory in test mode.
    var driver: Driver = MockData.driver

    /// Active session. Its role is the single gate that opens an interface.
    var session: StaffSession?
    /// Credential enrolled on this device for biometric unlock.
    var enrolledAccountId: String?
    var vehicles: [Vehicle] = []
    var activeShift: ActiveShift?
    var history: [ShiftRecord] = []
    var incomes: [IncomeEntry] = []
    var incidents: [Incident] = []
    var notices: [Notice] = []
    /// Used-unit credit contract; `nil` while the driver has not signed one.
    var credit: CreditAccount?
    /// Reports generated by the station supervisor; they break the vehicle-care bonus.
    var supervisorReports: [SupervisorReport] = []
    /// Days reserved in the bonus recovery program.
    var recoveryBookings: [RecoveryBooking] = []
    /// Bonus weeks already announced, so the popup is shown only once.
    var notifiedBonusWeeks: [String] = []
    /// Unit the station tied to this driver. Written by the supervisor, read here.
    var unitAssignment: VehicleAssignment?
    /// Demo-only offset applied to the device clock so every shift rule can be reviewed.
    var clockOffsetMinutes: Int = 0
    /// Set right after an explicit sign out: the access screen then waits for a
    /// credential choice instead of unlocking the same role again by itself.
    var awaitsCredentialChoice: Bool = false

    init() {
        let seedDate = Date()
        let seedHistory = MockData.shiftHistory(driver: MockData.driver, now: seedDate)

        if let restored = Self.restore() {
            apply(restored)
        } else {
            vehicles = MockData.syncOdometers(vehicles: MockData.vehicles, history: seedHistory)
            history = seedHistory
            incomes = MockData.incomeHistory(driver: MockData.driver, history: seedHistory)
            incidents = MockData.incidents(driver: MockData.driver, now: seedDate)
            notices = MockData.notices(now: seedDate)
            supervisorReports = MockData.supervisorReports(now: seedDate)
        }
        // A restored session carries only an account id: the driver profile is not
        // persisted, so it has to be resolved again from the credential. Without this the
        // app relaunches on `MockData.driver`, which is session-blind — in test mode that
        // is the laboratory's first driver, or `drv-none`, never the signed-in one.
        adoptSessionDriver()
        reloadAssignment()
    }

    /// Aligns `driver` with the credential of the open session.
    ///
    /// Only ever runs for a driver session, and only overwrites when the environment can
    /// actually answer for that credential; anything else leaves the current profile
    /// untouched.
    private func adoptSessionDriver() {
        guard let account = currentAccount, account.role == .driver else { return }
        guard let profile = MockData.driver(for: account) else { return }
        driver = profile
    }

    // MARK: - Unit assignment

    /// Pulls the assignment the supervisor wrote.
    ///
    /// What the station wrote always wins, unconditionally — this never overrides, edits
    /// or discards a stored record, not even one pointing at a unit the current
    /// environment does not hold. Tying a unit to a driver is the supervisor's act and
    /// this method never performs it, with the single scoped exception below.
    ///
    /// Without a stored record the driver has **no** unit: `unitAssignment` stays `nil`
    /// and the start screen says so. That is the correct operational state, and it is what
    /// every driver gets.
    func reloadAssignment() {
        if let stored = AssignmentBook.assignment(driverId: driver.id) {
            unitAssignment = stored
            return
        }
        guard let seeded = demoTitularUnit() else {
            unitAssignment = nil
            return
        }
        let assignment = AssignmentBook.make(
            stationId: driver.stationId,
            driverId: driver.id,
            driverName: driver.name,
            vehicleId: seeded.id,
            vehicleNumber: seeded.internalNumber,
            kind: .titular,
            note: "Asignación inicial del perfil de demostración.",
            assignedBy: "Supervisión de estación",
            now: now,
            previous: nil
        )
        AssignmentBook.upsert(assignment)
        unitAssignment = assignment
    }

    /// TEV-014 for Carlos Méndez Rivas, and for nobody else.
    ///
    /// One hardcoded pair, so the demonstration profile is navigable end to end without a
    /// supervisor session. This is **not** a general rule and must not become one: outside
    /// this exact driver and this exact unit, an unassigned driver stays unassigned, which
    /// is what the operational flow requires.
    ///
    /// The guards, in order: only the seeded demo driver — which is what confines this to
    /// one person in either environment — and only his titular unit, and only while that
    /// unit is still one of **his own** existing authorizations; the pair is checked
    /// against `authorizedVehicleIds`, never added to it.
    ///
    /// There is deliberately no environment guard. The demo credential now resolves to
    /// Carlos in test mode too, and a profile that opens without a unit there is precisely
    /// the failure this pairing exists to prevent. A laboratory driver is unaffected: he
    /// fails the identity guard on the first line.
    ///
    /// The remaining checks mirror the non-temporal blocking rules of
    /// `ShiftRules.validateUnit`: same station, free, operational, not held by another
    /// driver in the station's book. Seeding a unit that fails one of them would plant a
    /// permanent blocker on the start screen — worse than no unit. The temporal rule is
    /// deliberately excluded: the assignment exists at every hour, and the start window is
    /// judged when the driver actually tries to start.
    private func demoTitularUnit() -> Vehicle? {
        guard driver.id == MockData.seededDriver.id else { return nil }

        let unitId = MockData.seededTitularVehicleId
        guard driver.authorizedVehicleIds.contains(unitId) else { return nil }
        guard let vehicle = vehicles.first(where: { $0.id == unitId }) else { return nil }
        guard vehicle.stationId == driver.stationId else { return nil }
        guard vehicle.status == .available else { return nil }
        guard vehicle.occupiedBy == nil || vehicle.occupiedBy == driver.id else { return nil }
        // Not tied to another driver in the station's book.
        if let holder = AssignmentBook.holder(vehicleId: unitId), holder.driverId != driver.id {
            return nil
        }
        return vehicle
    }

    /// The unit the driver must take today: the substitute while it lasts, the titular one otherwise.
    var assignedVehicle: Vehicle? {
        guard let unitAssignment else { return nil }
        return vehicles.first { $0.id == unitAssignment.vehicleId }
    }

    var hasAssignedUnit: Bool { assignedVehicle != nil }

    /// Unit shown on the home screen: the one being driven, or the fixed one.
    var displayVehicle: Vehicle? { activeVehicle ?? assignedVehicle }

    // MARK: - Session scope

    var isAuthenticated: Bool { session != nil }

    var currentAccount: StaffAccount? { StaffDirectory.account(id: session?.accountId) }

    var currentRole: StaffRole? { session?.role }

    var currentStation: Station? { StaffDirectory.station(id: session?.stationId) }

    /// Account allowed to unlock this device with Face ID, if any.
    var enrolledAccount: StaffAccount? { StaffDirectory.account(id: enrolledAccountId) }

    /// Interfaces are opened by role only: a driver can never render a supervisor screen.
    func hasAccess(to role: StaffRole) -> Bool { session?.role == role }

    /// The driver profile is exposed only inside a driver session.
    var driverProfile: Driver? {
        guard let account = currentAccount, account.role == .driver, account.driverId == driver.id else { return nil }
        return driver
    }

    // MARK: - Derived values

    /// Time the app obeys. It never comes from the phone: in production it is real time
    /// and in a simulation it is the logical time of the test environment, shared by every
    /// role and every device.
    ///
    /// **A pure read.** It answers what hour it is and registers no SwiftUI dependency.
    ///
    /// It used to read `ClockSignal.generation` first. That was load-bearing at the time and
    /// is deliberately gone now: one indiscriminate counter meant any adopted clock state
    /// invalidated every reader of `store.now` at once, across all seven roles — and worse,
    /// screens inherited temporal correctness by accident, through a side effect none of
    /// them named. Views that genuinely follow the clock now say so, one at a time, with
    /// `TimeScope` or `ClockAnchor`.
    ///
    /// Use this for **action time**: the instant a decision is taken, a form is preloaded, a
    /// snapshot is rebuilt or a seed key is computed. Never to make something on screen move
    /// by itself — nothing observes this any more, and nothing should.
    var now: Date {
        AppClock.now()
    }

    var activeVehicle: Vehicle? {
        guard let shift = activeShift else { return nil }
        return vehicles.first { $0.id == shift.vehicleId }
    }

    var unreadNoticeCount: Int { notices.filter { !$0.read }.count }

    var hasCredit: Bool { credit != nil }

    /// Transparent contract metrics for the credit panel.
    var creditMetrics: CreditMetrics? {
        guard let credit else { return nil }
        return CreditProgram.metrics(for: credit, now: now)
    }

    var goals: ShiftRules.Goals { ShiftRules.goals(for: driver.group) }

    func elapsedSeconds(at date: Date) -> Int {
        guard let shift = activeShift else { return 0 }
        return max(0, Int(date.timeIntervalSince(shift.startedAt)))
    }

    func estimatedKmDriven(at date: Date) -> Int {
        Int((Double(elapsedSeconds(at: date)) / 60 * Self.simulatedKmPerMinute).rounded())
    }

    var capturedPhotoCount: Int { activeShift?.photos.count ?? 0 }

    /// The start of shift only needs the odometer and the battery readings.
    var isInspectionComplete: Bool {
        guard let shift = activeShift else { return false }
        return InspectionSlot.driverSlots.allSatisfy { shift.photos[$0.rawValue] != nil }
    }

    /// Monday → Sunday late-minute log, the "bitácora" shown in Historial.
    struct LateDay: Identifiable, Sendable {
        let date: Date
        let label: String
        let minutes: Int
        let paidBackMinutes: Int
        let hasShift: Bool

        var id: Date { date }
        var pendingMinutes: Int { max(0, minutes - paidBackMinutes) }
    }

    func weeklyLateBreakdown(reference: Date) -> [LateDay] {
        let calendar = ShiftRules.calendar
        let start = ShiftRules.weekStart(for: reference)
        return (0..<7).compactMap { offset in
            guard let day = calendar.date(byAdding: .day, value: offset, to: start) else { return nil }
            let record = history.first { ShiftRules.isSameDay($0.startedAt, day) }
            return LateDay(
                date: day,
                label: Fmt.dayShort(day),
                minutes: record?.lateMinutes ?? 0,
                paidBackMinutes: record?.paidBackMinutes ?? 0,
                hasShift: record != nil
            )
        }
    }

    func weeklyLateDebt(reference: Date) -> Int {
        weeklyLateBreakdown(reference: reference).reduce(0) { $0 + $1.pendingMinutes }
    }

    func earnedToday(reference: Date) -> Int {
        let fromIncomes = incomes
            .filter { ShiftRules.isSameDay($0.date, reference) }
            .reduce(0) { $0 + $1.amountMxn }
        let fromClosedShifts = history
            .filter { ShiftRules.isSameDay($0.startedAt, reference) }
            .reduce(0) { $0 + $1.earningsMxn }
        return max(fromIncomes, fromClosedShifts, activeShift?.earningsMxn ?? 0)
    }

    func tripsToday(reference: Date) -> Int {
        let fromIncomes = incomes
            .filter { ShiftRules.isSameDay($0.date, reference) }
            .reduce(0) { $0 + $1.trips }
        return max(fromIncomes, activeShift?.trips ?? 0)
    }

    func earnedThisWeek(reference: Date) -> Int {
        incomes
            .filter { ShiftRules.isInSameWeek($0.date, as: reference) }
            .reduce(0) { $0 + $1.amountMxn }
    }

    struct DayEarnings: Identifiable, Sendable {
        let label: String
        let amount: Int
        let isToday: Bool
        let date: Date

        var id: Date { date }
    }

    func weeklyEarningsByDay(reference: Date) -> [DayEarnings] {
        let calendar = ShiftRules.calendar
        let start = ShiftRules.weekStart(for: reference)
        return (0..<7).compactMap { offset in
            guard let day = calendar.date(byAdding: .day, value: offset, to: start) else { return nil }
            let amount = incomes
                .filter { ShiftRules.isSameDay($0.date, day) }
                .reduce(0) { $0 + $1.amountMxn }
            return DayEarnings(
                label: Fmt.dayShort(day),
                amount: amount,
                isToday: ShiftRules.isSameDay(day, reference),
                date: day
            )
        }
    }

    // MARK: - Session

    /// Opens the session for an already authenticated account and links the device
    /// so future biometric unlocks resolve to this same credential.
    func signIn(account: StaffAccount, method: SignInMethod) {
        if let profile = MockData.driver(for: account) {
            driver = profile
        } else if LabRuntime.isTest, account.role == .driver {
            driver = MockData.driver
        }
        defer { reloadAssignment() }
        session = StaffSession(
            accountId: account.id,
            role: account.role,
            stationId: account.stationId,
            method: method,
            startedAt: Date()
        )
        enrolledAccountId = account.id
        awaitsCredentialChoice = false
        persist()
    }

    /// Closes the session and returns to the access screen. The automatic scan is held
    /// back so another role can be identified instead of re-entering the same one.
    func signOut() {
        session = nil
        awaitsCredentialChoice = true
        persist()
    }

    /// Removes the biometric link so the next access requires full credentials.
    func forgetDevice() {
        enrolledAccountId = nil
        session = nil
        awaitsCredentialChoice = true
        persist()
    }

    /// Rebuilds the operational state from the active environment. Called whenever the
    /// laboratory changes the world so every interface reflects it immediately.
    func adoptEnvironment() {
        defer { reloadAssignment() }
        // Same reasoning as in `init`: the session outlives the environment switch, so the
        // profile is resolved from the credential and only falls back to the
        // environment's default driver when the credential has none.
        driver = MockData.driver
        adoptSessionDriver()
        let source = MockData.vehicles
        let activeVehicleId = activeShift?.vehicleId

        vehicles = source.map { incoming in
            guard let kept = vehicles.first(where: { $0.id == incoming.id }) else { return incoming }
            // A unit inside a running shift keeps its live readings; every other unit
            // follows the environment, so lab edits land immediately.
            guard kept.id != activeVehicleId, LabRuntime.isTest else { return kept }
            return incoming
        }

        if let shift = activeShift, !vehicles.contains(where: { $0.id == shift.vehicleId }) {
            activeShift = nil
        }
        persist()
    }

    /// Wipes every operational record of the driver interface, leaving it at zero.
    func clearOperationalData() {
        vehicles = MockData.vehicles
        activeShift = nil
        history = []
        incomes = []
        incidents = []
        notices = []
        credit = nil
        supervisorReports = []
        recoveryBookings = []
        notifiedBonusWeeks = []
        clockOffsetMinutes = 0
        driver = MockData.driver
        AssignmentBook.clear()
        unitAssignment = nil
        persist()
    }

    func setClockOffset(minutes: Int) {
        clockOffsetMinutes = minutes
        persist()
    }

    /// Keeps the persisted offset in step with the logical hour.
    ///
    /// This is **not** the invalidation mechanism any more. An integer number of minutes
    /// cannot express a second, a speed, a pause or a new revision landing on the same
    /// minute, so driving the interface from it left every one of those changes invisible.
    /// `ClockSignal` does the invalidating; this only maintains stored state.
    func syncSimulationClock() {
        let offset = AppClock.offsetMinutes()
        guard clockOffsetMinutes != offset else { return }
        clockOffsetMinutes = offset
        persist()
    }

