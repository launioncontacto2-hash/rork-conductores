    // MARK: - Notices

    func markNoticeRead(id: String) {
        guard let index = notices.firstIndex(where: { $0.id == id }) else { return }
        notices[index].read = true
        persist()
    }

    /// Marks read only what this session can actually see. A notice belonging to another
    /// environment is not the reader's to dismiss.
    func markAllNoticesRead() {
        let visible = Set(visibleNotices.map(\.id))
        notices = notices.map { notice in
            guard visible.contains(notice.id) else { return notice }
            var updated = notice
            updated.read = true
            return updated
        }
        persist()
    }

    /// Publishes a notice in the station's voice — and the single frontier where that is
    /// decided, for every producer in the app.
    ///
    /// There are eighteen call sites across five stores, and auditing them one by one
    /// found the same shape each time: an operation succeeds locally and narrates itself
    /// as received by an authority. "Incidencia enviada a la estación." "Reserva
    /// confirmada." "Crédito aprobado." "Depósito notificado a gerencia." Gating each one
    /// separately would mean eighteen chances to forget, and every new feature would be
    /// a nineteenth. So the refusal lives here, once, where the sentence is minted.
    ///
    /// Returns whether anything was published, rather than throwing: a notice is a
    /// side effect of an operation that has already made its own decision, and forcing
    /// every caller into `try?` would hide the refusal instead of stating it. Callers
    /// that show a confirmation to the driver — `notifySupervisor`, `bookRecovery` — read
    /// this and say something true instead.
    @discardableResult
    func pushNotice(kind: NoticeKind, title: String, body: String) -> Bool {
        guard canPublishStationNotices else { return false }
        notices.insert(
            Notice(
                id: "not-\(UUID().uuidString.prefix(8))",
                kind: kind,
                title: title,
                body: body,
                createdAt: now,
                read: false,
                origin: noticeAuthority.origin
            ),
            at: 0
        )
        persist()
        return true
    }

    // MARK: - Persistence

    private func apply(_ state: PersistedState) {
        // A backend session is not restored from disk. Identity there is proved by a live
        // exchange with Supabase Auth, and no credential is kept to repeat it, so a
        // restored one would be a driver the app can no longer vouch for. It is dropped
        // and the access screen asks for credentials again; every operational record in
        // the same payload is kept untouched.
        if state.session?.principal == nil {
            session = state.session
        } else {
            session = nil
            // Never hand the relaunch to a biometric unlock of a different identity.
            awaitsCredentialChoice = true
        }
        enrolledAccountId = state.enrolledAccountId
        applyOperational(state)
        clockOffsetMinutes = state.clockOffsetMinutes
    }

    private func applyOperational(_ state: PersistedState) {
        vehicles = state.vehicles
        activeShift = state.activeShift
        history = state.history
        incomes = state.incomes
        incidents = state.incidents
        notices = state.notices
        credit = Self.demoAttributed(state.credit, driverId: driver.id)
        supervisorReports = state.supervisorReports
        recoveryBookings = state.recoveryBookings
        notifiedBonusWeeks = state.notifiedBonusWeeks
    }

    /// An operation with nothing in it. What a driver who has never worked must see.
    nonisolated private static func emptyOperationalState() -> PersistedState {
        PersistedState(
            session: nil,
            enrolledAccountId: nil,
            vehicles: [],
            activeShift: nil,
            history: [],
            incomes: [],
            incidents: [],
            notices: [],
            credit: nil,
            clockOffsetMinutes: 0,
            supervisorReports: [],
            recoveryBookings: [],
            notifiedBonusWeeks: []
        )
    }

    /// Names a contract stored before ownership existed.
    ///
    /// This only ever runs on the demonstration key — an identity restores through
    /// `ownedState`, which never adopts an unattributed contract — so a nameless
    /// contract can only have been written by a demonstration session, and belongs to
    /// the demonstration driver. It is never promoted out of `.simulated`: naming a
    /// fixture does not make it authoritative, it only lets the demo wallet keep
    /// discounting the contract Carlos already had.
    nonisolated private static func demoAttributed(_ credit: CreditAccount?, driverId: String) -> CreditAccount? {
        guard let credit else { return nil }
        guard !credit.isAttributed, credit.origin == .simulated else { return credit }
        return credit.attributed(to: driverId)
    }

    /// Keeps only what can be **proved** to belong to `driverId`.
    ///
    /// Records that carry a `driverId` are filtered by it. Everything else starts empty
    /// unless it was written under this identity's own key.
    ///
    /// **Credit restoration rule, adopted in 15B.10.** A stored contract is restored
    /// only if it names this driver as its owner **and** its provenance is `.backend`.
    /// Ownership on its own is not enough: a `.simulated` contract carrying the right
    /// owner string is still a fixture minted on this phone, and a matching string is
    /// not an authority vouching for a debt. Since nothing can legitimately produce a
    /// `.backend` contract yet, a backend session still ends up with no credit — but now
    /// because the rule says so, instead of because the model could not tell.
    ///
    /// The fleet inventory starts empty as well. A real station's units are the backend's
    /// to hand out; borrowing the demonstration catalogue is exactly how a driver ends up
    /// looking at a unit nobody ever assigned to them.
    nonisolated private static func ownedState(
        _ stored: PersistedState?,
        driverId: String,
        capability: OperationalCapability,
        noticeAuthority: NoticeAuthority
    ) -> PersistedState {
        var owned = emptyOperationalState()
        guard let stored else { return owned }

        // Deliberately **not** `stored.vehicles`. The comment above has said since 15B.10
        // that the inventory starts empty, but the code restored whatever was on disk — so
        // one demonstration catalogue leaking in through an environment switch became
        // permanent the moment `persist()` ran. Nothing is deleted: the stored array stays
        // on disk, it is simply not adopted until a server catalogue exists to fill it.
        owned.vehicles = []
        // Ownership is no longer enough for the operational cycle. `driverId` says whose
        // row it is; it cannot say whether the day happened. A simulated block carrying
        // the exact `profileId` of the proved identity — which is precisely what a
        // laboratory run by that identity produces — used to restore straight into
        // production, where it became history, a settlement and a bonus verdict. It is
        // not deleted: it stays in the blob, and it comes back the moment the laboratory
        // asks for it.
        owned.activeShift = OperationalRecordRules.shift(
            stored.activeShift,
            driverId: driverId,
            capability: capability
        )
        owned.history = OperationalRecordRules.history(
            stored.history,
            driverId: driverId,
            capability: capability
        )
        owned.incomes = stored.incomes.filter { $0.driverId == driverId }
        owned.incidents = OperationalRecordRules.incidents(
            stored.incidents,
            driverId: driverId,
            capability: capability
        )
        owned.credit = stored.credit.flatMap { $0.driverId == driverId && $0.origin == .backend ? $0 : nil }
        // No ownership field of their own — the container establishes whose they are — so
        // provenance is the only question left, and it is the one that matters: a bell
        // full of "enviado", "aprobado" and "confirmado" written by a laboratory run is
        // the most persuasive thing this app can show a driver, and the least true. The
        // rows stay on disk and come back with their own environment.
        owned.notices = NoticeRules.visible(stored.notices, authority: noticeAuthority)
        owned.supervisorReports = stored.supervisorReports
        owned.recoveryBookings = stored.recoveryBookings
        owned.notifiedBonusWeeks = stored.notifiedBonusWeeks
        return owned
    }

    private func persist() {
        persist(key: storageKey)
    }

    private func persist(key: String) {
        let state = PersistedState(
            session: session,
            enrolledAccountId: enrolledAccountId,
            vehicles: vehicles,
            activeShift: activeShift,
            history: history,
            incomes: incomes,
            incidents: incidents,
            notices: notices,
            credit: credit,
            clockOffsetMinutes: clockOffsetMinutes,
            supervisorReports: supervisorReports,
            recoveryBookings: recoveryBookings,
            notifiedBonusWeeks: notifiedBonusWeeks
        )
        do {
            let encoder = JSONEncoder()
            encoder.dateEncodingStrategy = .iso8601
            let data = try encoder.encode(state)
            defaults.set(data, forKey: key)
        } catch {
            print("No se pudo guardar el estado local: \(error.localizedDescription)")
        }
    }

    nonisolated private static func restore(key: String, defaults: UserDefaults) -> PersistedState? {
        guard let data = defaults.data(forKey: key) else { return nil }
        do {
            let decoder = JSONDecoder()
            decoder.dateDecodingStrategy = .iso8601
            return try decoder.decode(PersistedState.self, from: data)
        } catch {
            print("No se pudo leer el estado local: \(error.localizedDescription)")
            return nil
        }
    }
