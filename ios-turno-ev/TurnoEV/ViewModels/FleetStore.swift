    func finishShift(endOdometerKm: Int, endBatteryPct: Int, photo: Data?) -> ShiftSummary {
        guard let shift = activeShift else {
            return ShiftSummary(
                kmDriven: 0,
                durationMinutes: 0,
                earningsMxn: 0,
                trips: 0,
                dailyGoalMxn: goals.dailyMxn,
                missingMxn: goals.dailyMxn,
                missingTrips: goals.tripsPerDay,
                lateMinutes: 0
            )
        }

        let endedAt = now
        let record = ShiftRecord(
            id: shift.id,
            driverId: shift.driverId,
            vehicleId: shift.vehicleId,
            vehicleInternalNumber: activeVehicle?.internalNumber ?? "—",
            group: shift.group,
            slot: shift.slot,
            scheduledStartAt: shift.scheduledStartAt,
            startedAt: shift.startedAt,
            endedAt: endedAt,
            lateMinutes: shift.lateMinutes,
            paidBackMinutes: 0,
            startOdometerKm: shift.startOdometerKm,
            endOdometerKm: endOdometerKm,
            startBatteryPct: shift.startBatteryPct,
            endBatteryPct: endBatteryPct,
            trips: shift.trips,
            earningsMxn: shift.earningsMxn
        )

        history.insert(record, at: 0)
        if let index = vehicles.firstIndex(where: { $0.id == shift.vehicleId }) {
            vehicles[index].status = .available
            vehicles[index].occupiedBy = nil
            vehicles[index].odometerKm = endOdometerKm
            vehicles[index].batteryPct = endBatteryPct
        }
        if photo != nil {
            // Final odometer evidence is archived with the closed shift record.
            pushNotice(
                kind: .station,
                title: "Turno cerrado",
                body: "Entregaste \(record.vehicleInternalNumber) con \(Fmt.km(endOdometerKm)). Duración \(Fmt.durationText(record.durationMinutes))."
            )
        }
        activeShift = nil
        persist()

        return ShiftSummary(
            kmDriven: record.kmDriven,
            durationMinutes: record.durationMinutes,
            earningsMxn: record.earningsMxn,
            trips: record.trips,
            dailyGoalMxn: goals.dailyMxn,
            missingMxn: max(0, goals.dailyMxn - record.earningsMxn),
            missingTrips: max(0, goals.tripsPerDay - record.trips),
            lateMinutes: record.lateMinutes
        )
    }

    /// Applies paid-back minutes to the oldest pending late day of the current week.
    @discardableResult
    func payLateTime(minutes: Int) -> Int {
        var remaining = minutes
        var applied = 0
        let weekDays = weeklyLateBreakdown(reference: now).filter { $0.pendingMinutes > 0 }
        let pendingDates = weekDays.map(\.date)

        for index in history.indices where remaining > 0 {
            let record = history[index]
            guard pendingDates.contains(where: { ShiftRules.isSameDay($0, record.startedAt) }) else { continue }
            let pending = record.pendingLateMinutes
            guard pending > 0 else { continue }
            let pay = min(pending, remaining)
            history[index].paidBackMinutes += pay
            remaining -= pay
            applied += pay
        }

        if applied > 0 { persist() }
        return applied
    }

