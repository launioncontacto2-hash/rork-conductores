    /// Closes the three-step flow: opens the shift and files the captured evidence.
    @discardableResult
    func startShift(
        vehicle: Vehicle,
        odometerKm: Int,
        batteryPct: Int,
        odometerPhoto: Data?,
        batteryPhoto: Data?
    ) -> ActiveShift {
        let shift = assign(vehicle: vehicle, odometerKm: odometerKm, batteryPct: batteryPct)
        if let odometerPhoto { saveInspectionPhoto(slot: .odometer, data: odometerPhoto) }
        if let batteryPhoto { saveInspectionPhoto(slot: .battery, data: batteryPhoto) }
        return activeShift ?? shift
    }

    @discardableResult
    func assign(vehicle: Vehicle, odometerKm: Int, batteryPct: Int) -> ActiveShift {
        let startedAt = now
        let scheduled = ShiftRules.scheduledStart(slot: driver.slot, on: startedAt)
        let shift = ActiveShift(
            id: "shift-\(UUID().uuidString.prefix(8))",
            driverId: driver.id,
            vehicleId: vehicle.id,
            group: ShiftRules.group(for: startedAt),
            slot: driver.slot,
            scheduledStartAt: scheduled,
            startedAt: startedAt,
            lateMinutes: ShiftRules.lateMinutes(scheduled: scheduled, actual: startedAt),
            startOdometerKm: odometerKm,
            startBatteryPct: batteryPct,
            photos: [:],
            trips: 0,
            earningsMxn: 0
        )

        activeShift = shift
        if let index = vehicles.firstIndex(where: { $0.id == vehicle.id }) {
            vehicles[index].status = .occupied
            vehicles[index].occupiedBy = driver.id
            vehicles[index].odometerKm = odometerKm
            vehicles[index].batteryPct = batteryPct
        }

        if shift.lateMinutes > 0 {
            pushNotice(
                kind: .reminder,
                title: "Inicio de turno con atraso",
                body: "Iniciaste \(shift.lateMinutes) minutos después de la hora programada. Se registró en tu bitácora."
            )
        }

        persist()
        return shift
    }

    func saveInspectionPhoto(slot: InspectionSlot, data: Data) {
        guard var shift = activeShift else { return }
        shift.photos[slot.rawValue] = data
        activeShift = shift
        persist()
    }

    func registerIncome(amountMxn: Int, trips: Int, platform: IncomePlatform, evidence: Data?, note: String? = nil) {
        let entry = IncomeEntry(
            id: "inc-\(UUID().uuidString.prefix(8))",
            driverId: driver.id,
            shiftId: activeShift?.id,
            date: now,
            amountMxn: amountMxn,
            trips: trips,
            platform: platform,
            evidence: evidence,
            note: note
        )
        incomes.insert(entry, at: 0)

        if var shift = activeShift {
            shift.earningsMxn += amountMxn
            shift.trips += trips
            activeShift = shift
        }
        persist()
    }

    /// The account direction publishes for cash that could not be charged by card.
    var cashDepositAccount: CashDepositAccount { NationalCashBoard.current }

    /// Cash trips the platform reported and that are still in the driver's hands.
    var openCashCharges: [CashCharge] {
        CashChargeLedger.open(driverId: driver.id)
    }

    /// Simulates the platform reporting a trip settled in cash during the shift.
    @discardableResult
    func syncCashChargeFromPlatform(amountMxn: Int) -> CashCharge {
        let charge = CashChargeLedger.make(
            driverId: driver.id,
            stationId: driver.stationId,
            amountMxn: amountMxn,
            now: now
        )
        CashChargeLedger.add(charge)
        pushNotice(
            kind: .station,
            title: "Viaje cobrado en efectivo",
            body: "\(charge.tripReference) por \(Fmt.mxn(amountMxn)). Deposítalo hoy antes de las 23:59:59 o se descontará de tus ingresos de la semana."
        )
        return charge
    }

    /// Closes every cash charge whose day already ended without a deposit. From here the
    /// amount stops being a pending deposit and becomes a discount on the week, visible
    /// in the wallet as "Cobro de viaje en efectivo".
    @discardableResult
    func chargeBackExpiredCashCharges() -> [CashCharge] {
        let expired = openCashCharges.filter { now > CashChargeRules.deadline(for: $0) }
        guard !expired.isEmpty else { return [] }

        for charge in expired {
            CashChargeLedger.markChargedBack(id: charge.id, at: now)
            pushNotice(
                kind: .credit,
                title: "\(CashChargeRules.recoveryConcept) · \(Fmt.mxn(charge.amountMxn))",
                body: "El viaje \(charge.tripReference) del \(Fmt.dateShort(charge.generatedAt)) no se depositó el mismo día. El monto se descuenta de tus ingresos al cierre de la semana."
            )
        }
        return expired
    }

    /// Files a cash deposit: the income enters the day, the slip stays attached and the
    /// manager of the station is notified in the same movement. Cash is not an authorized
    /// way to charge, so every peso received in hand has to leave a trace.
    @discardableResult
    func registerCashDeposit(
        charge: CashCharge,
        declaredMxn: Int,
        detectedMxn: Int?,
        match: DepositMatch,
        accountMatch: DepositMatch,
        detectedAccount: String?,
        slip: Data?
    ) -> CashDeposit {
        let account = cashDepositAccount
        let deposit = CashDeposit(
            id: "dep-\(UUID().uuidString.prefix(8))",
            stationId: driver.stationId,
            driverId: driver.id,
            driverName: driver.name,
            vehicleNumber: displayVehicle?.internalNumber ?? "Sin unidad",
            declaredMxn: declaredMxn,
            detectedMxn: detectedMxn,
            match: match,
            accountMatch: accountMatch,
            detectedAccount: detectedAccount,
            bank: account.bank,
            clabe: account.clabe,
            createdAt: now,
            slip: slip,
            acknowledgedAt: nil
        )
        CashDepositLedger.record(deposit)
        CashChargeLedger.markDeposited(id: charge.id, at: now)

        registerIncome(
            amountMxn: declaredMxn,
            trips: 0,
            platform: .cash,
            evidence: slip,
            note: "\(charge.tripReference) · depósito en \(account.bank)"
        )

        pushNotice(
            kind: .station,
            title: "Depósito en efectivo notificado a gerencia",
            body: "\(Fmt.mxn(declaredMxn)) del viaje \(charge.tripReference) depositados en \(account.bank). El gerente de \(driver.station) recibió el comprobante."
        )
        return deposit
    }

