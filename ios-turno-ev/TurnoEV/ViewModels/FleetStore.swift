    /// Closes the three-step flow: opens the shift and files the captured evidence.
    ///
    /// **The whole write is behind one guard.** Opening a shift is not one record: it
    /// mints an `ActiveShift`, flips a vehicle to `.occupied`, writes `occupiedBy`,
    /// overwrites the unit's odometer and battery with numbers typed on this phone,
    /// files two photographs as evidence and may register a late arrival that costs a
    /// bonus. Every one of those is asserted to be a fact of the station's day. So the
    /// refusal is taken here, before the first of them.
    ///
    /// The unit checks stay after it and unchanged: inside a simulation the shift is
    /// still only openable on the unit actually assigned.
    @discardableResult
    func startShift(
        vehicle: Vehicle,
        odometerKm: Int,
        batteryPct: Int,
        odometerPhoto: Data?,
        batteryPhoto: Data?
    ) throws -> ActiveShift {
        guard canRunOperationalCycle else { throw OperationalMutationError.backendRequired }
        guard let assigned = unitAssignment, assigned.vehicleId == vehicle.id else {
            throw UnitAssignmentError.unitNotAssigned
        }
        guard vehicles.contains(where: { $0.id == vehicle.id }) else {
            throw UnitAssignmentError.unitNotAssigned
        }
        let shift = assign(vehicle: vehicle, odometerKm: odometerKm, batteryPct: batteryPct)
        if let odometerPhoto { saveInspectionPhoto(slot: .odometer, data: odometerPhoto) }
        if let batteryPhoto { saveInspectionPhoto(slot: .battery, data: batteryPhoto) }
        return activeShift ?? shift
    }

    /// The write itself, with no boundary of its own.
    ///
    /// Private since 15B.13.3: it was reachable from anywhere, and it is the method that
    /// actually opens a shift and takes a vehicle. Every caller now has to cross
    /// `startShift` — where the refusal lives — instead of arriving here directly.
    @discardableResult
    private func assign(vehicle: Vehicle, odometerKm: Int, batteryPct: Int) -> ActiveShift {
        let startedAt = now
        let scheduled = ShiftRules.scheduledStart(slot: driver.slot, on: startedAt)
        let shift = ActiveShift(
            id: "shift-\(UUID().uuidString.prefix(8))",
            driverId: driver.id,
            vehicleId: vehicle.id,
            group: ShiftRules.group(for: startedAt),
            slot: driver.slot,
            scheduledStartAt: scheduled,
            startedAt: startedAt,
            lateMinutes: ShiftRules.lateMinutes(scheduled: scheduled, actual: startedAt),
            startOdometerKm: odometerKm,
            startBatteryPct: batteryPct,
            photos: [:],
            trips: 0,
            earningsMxn: 0,
            origin: operationalOrigin
        )

        activeShift = shift
        if let index = vehicles.firstIndex(where: { $0.id == vehicle.id }) {
            vehicles[index].status = .occupied
            vehicles[index].occupiedBy = driver.id
            vehicles[index].odometerKm = odometerKm
            vehicles[index].batteryPct = batteryPct
        }

        if shift.lateMinutes > 0 {
            pushNotice(
                kind: .reminder,
                title: "Inicio de turno con atraso",
                body: "Iniciaste \(shift.lateMinutes) minutos después de la hora programada. Se registró en tu bitácora."
            )
        }

        persist()
        return shift
    }

    /// Files evidence onto the open shift.
    ///
    /// Gated too, even though a production session cannot have a shift to attach to: a
    /// photograph stored against a shift record *is* the evidence the station is told it
    /// has, and a legacy simulated shift standing in memory must not be able to collect
    /// more of it under a proved identity.
    func saveInspectionPhoto(slot: InspectionSlot, data: Data) {
        guard canRunOperationalCycle, canActOnActiveShift else { return }
        guard var shift = activeShift else { return }
        shift.photos[slot.rawValue] = data
        activeShift = shift
        persist()
    }

    /// Files an income the driver declares.
    ///
    /// This is the most load-bearing write in the app and the reason 15B.10 exists. An
    /// income does not merely add pesos: it is what makes the week count as worked, and
    /// a worked week unlocks the station deduction and satisfies the gate the bonuses
    /// stand on. One fabricated entry moves four bonuses out of "sin evaluar" and into
    /// payable. So a session that cannot vouch for the money cannot file it.
    func registerIncome(
        amountMxn: Int,
        trips: Int,
        platform: IncomePlatform,
        evidence: Data?,
        note: String? = nil
    ) throws {
        guard canSimulateFinancialState else { throw FinancialMutationError.backendRequired }
        appendIncome(amountMxn: amountMxn, trips: trips, platform: platform, evidence: evidence, note: note)
    }

    /// The write itself, with no boundary of its own.
    ///
    /// Separated from `registerIncome` so that every caller has to have crossed the
    /// boundary explicitly before reaching it, rather than swallowing a thrown refusal
    /// with `try?` and leaving no trace of the decision.
    private func appendIncome(
        amountMxn: Int,
        trips: Int,
        platform: IncomePlatform,
        evidence: Data?,
        note: String?
    ) {
        let entry = IncomeEntry(
            id: "inc-\(UUID().uuidString.prefix(8))",
            driverId: driver.id,
            origin: ledgerOrigin,
            shiftId: activeShift?.id,
            date: now,
            amountMxn: amountMxn,
            trips: trips,
            platform: platform,
            evidence: evidence,
            note: note
        )
        incomes.insert(entry, at: 0)

        if var shift = activeShift {
            shift.earningsMxn += amountMxn
            shift.trips += trips
            activeShift = shift
        }
        persist()
    }

