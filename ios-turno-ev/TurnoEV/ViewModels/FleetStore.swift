import Foundation
import Observation

/// Why a proved identity was still not allowed to open a session.
///
/// A driver whose membership is incomplete is a data problem, not a login the app may
/// paper over: nothing here is defaulted, so the session simply does not open and the
/// reason is legible on the access screen.
nonisolated enum SessionOpenError: LocalizedError, Sendable {
    case missingStation
    case missingStationName
    case missingShiftGroup
    case missingShiftSlot

    var errorDescription: String? {
        switch self {
        case .missingStation:
            return "Tu cuenta no tiene estación asignada. Contacta a tu supervisor."
        case .missingStationName:
            return "La estación de tu cuenta no tiene nombre registrado. Contacta a tu supervisor."
        case .missingShiftGroup:
            return "Tu cuenta no tiene grupo de turno asignado. Contacta a tu supervisor."
        case .missingShiftSlot:
            return "Tu cuenta no tiene horario de turno asignado. Contacta a tu supervisor."
        }
    }
}

/// Single source of truth for the driver session, the active shift and every log.
/// Persists to `UserDefaults` so a reopened app keeps the shift running.
@Observable
final class FleetStore {
    // MARK: - Persisted shape

    nonisolated private struct PersistedState: Codable, Sendable {
        var session: StaffSession?
        /// Account linked to this device; only it can unlock with Face ID.
        var enrolledAccountId: String?
        var vehicles: [Vehicle]
        var activeShift: ActiveShift?
        var history: [ShiftRecord]
        var incomes: [IncomeEntry]
        var incidents: [Incident]
        var notices: [Notice]
        var credit: CreditAccount?
        var clockOffsetMinutes: Int
        var supervisorReports: [SupervisorReport]
        var recoveryBookings: [RecoveryBooking]
        var notifiedBonusWeeks: [String]
    }

    /// Storage of the demonstration credentials. Untouched: everything a demo session
    /// ever wrote stays exactly where it was and keeps being read from here.
    private static let demoStorageKey = "turnoev.state.v4"

    /// Storage of one identity proved by the backend, in one environment.
    ///
    /// Derived from `profileId` — never from the email and never from the password — so
    /// the key is stable across renames and carries no credential. One driver per key is
    /// what makes "driver A never reads the state of driver B" a property of the storage
    /// itself instead of a filter someone has to remember to apply.
    ///
    /// The environment is part of the key for the same reason the driver is. A laboratory
    /// experiment run by a proved identity and that identity's real operation are two
    /// different operations, and separating them at the storage layer is what makes
    /// "nothing simulated survives the way back to production" and "nothing real is
    /// deleted on the way into the laboratory" properties of the container instead of
    /// clean-up code someone has to run. The production key is byte-for-byte the one that
    /// already exists: nothing stored needs migrating.
    nonisolated private static func identityStorageKey(profileId: String, environment: LabMode) -> String {
        switch environment {
        case .production: "\(demoStorageKey).\(profileId)"
        case .test: "\(demoStorageKey).lab.\(profileId)"
        }
    }

    /// Key this session uses in a given environment.
    ///
    /// A demonstration session answers the same key in both: it *is* the simulation, and
    /// giving it a second blob would change behaviour that is deliberately frozen.
    private func storageKey(for environment: LabMode) -> String {
        guard let profileId = session?.principal?.profileId else { return Self.demoStorageKey }
        return Self.identityStorageKey(profileId: profileId, environment: environment)
    }

    /// Key the open session reads from and writes to right now.
    private var storageKey: String { storageKey(for: adoptedEnvironment) }

    /// Average fleet speed used to estimate distance until real GPS/telemetry lands.
    private static let simulatedKmPerMinute = 0.32

    // MARK: - State

    /// Driver profile of the open session. It follows the active environment: seeded in
    /// production, created by the laboratory in test mode.
    var driver: Driver = MockData.driver

    /// Active session. Its role is the single gate that opens an interface.
    var session: StaffSession?
    /// Credential enrolled on this device for biometric unlock.
    var enrolledAccountId: String?
    var vehicles: [Vehicle] = []
    var activeShift: ActiveShift?
    var history: [ShiftRecord] = []
    var incomes: [IncomeEntry] = []
    var incidents: [Incident] = []
    var notices: [Notice] = []
    /// Used-unit credit contract; `nil` while the driver has not signed one.
    var credit: CreditAccount?
    /// Reports generated by the station supervisor; they break the vehicle-care bonus.
    var supervisorReports: [SupervisorReport] = []
    /// Days reserved in the bonus recovery program.
    var recoveryBookings: [RecoveryBooking] = []
    /// Bonus weeks already announced, so the popup is shown only once.
    var notifiedBonusWeeks: [String] = []
    /// Unit the station tied to this driver. Written by the supervisor, read here.
    var unitAssignment: VehicleAssignment?
    /// Demo-only offset applied to the device clock so every shift rule can be reviewed.
    var clockOffsetMinutes: Int = 0
    /// Set right after an explicit sign out: the access screen then waits for a
    /// credential choice instead of unlocking the same role again by itself.
    var awaitsCredentialChoice: Bool = false

    /// The one observable source of the execution environment. Read live by every
    /// capability below, so a change is visible to the same session immediately.
    private let environmentSource: RuntimeEnvironment

    /// Where this store persists. Injectable so a test never writes on a real device
    /// state; the app always passes `.standard`.
    private let defaults: UserDefaults

    /// Which environment the state **currently in memory** belongs to.
    ///
    /// Deliberately not a source of truth and never consulted by a capability: it only
    /// answers "which key was this loaded from", so the swap can write the outgoing state
    /// under the right key before reading the incoming one. `environmentSource` is the
    /// truth; this is a bookmark, refreshed by `adoptEnvironment()`.
    private var adoptedEnvironment: LabMode

    init(environment: RuntimeEnvironment = .shared, defaults: UserDefaults = .standard) {
        self.environmentSource = environment
        self.defaults = defaults
        self.adoptedEnvironment = environment.mode
        // The app always opens on the demonstration storage: a backend session is never
        // restored (see `apply`), so this is the only state that can be standing when the
        // access screen appears.
        if let restored = Self.restore(key: Self.demoStorageKey, defaults: defaults) {
            apply(restored)
        } else {
            seedDemoState()
        }
        // A restored session carries only an account id: the driver profile is not
        // persisted, so it has to be resolved again from the credential. Without this the
        // app relaunches on `MockData.driver`, which is session-blind — in test mode that
        // is the laboratory's first driver, or `drv-none`, never the signed-in one.
        adoptSessionDriver()
        // A contract stored before 15B.10 carries no owner. Now that the demonstration
        // profile is resolved, it can be named — see `demoAttributed`.
        credit = Self.demoAttributed(credit, driverId: driver.id)
        reloadAssignment()
    }

    /// Demonstration seeds, unchanged in content.
    ///
    /// Extracted from `init` so that leaving a backend session can rebuild them on a
    /// device that never stored a demonstration state of its own.
    private func seedDemoState() {
        let seedDate = Date()
        let seedHistory = MockData.shiftHistory(driver: MockData.driver, now: seedDate)
        vehicles = MockData.syncOdometers(vehicles: MockData.vehicles, history: seedHistory)
        activeShift = nil
        history = seedHistory
        incomes = MockData.incomeHistory(driver: MockData.driver, history: seedHistory)
        incidents = MockData.incidents(driver: MockData.driver, now: seedDate)
        notices = MockData.notices(now: seedDate)
        credit = nil
        supervisorReports = MockData.supervisorReports(now: seedDate)
        recoveryBookings = []
        notifiedBonusWeeks = []
    }

    /// Aligns `driver` with the credential of the open session.
    ///
    /// Only ever runs for a driver session, and only overwrites when the environment can
    /// actually answer for that credential; anything else leaves the current profile
    /// untouched.
    private func adoptSessionDriver() {
        // A backend session already carries its own driver, built from the principal the
        // server proved. The directory has no entry for that person and must never be
        // asked to supply one.
        guard session?.principal == nil else { return }
        guard let account = currentAccount, account.role == .driver else { return }
        guard let profile = MockData.driver(for: account) else { return }
        driver = profile
    }

    // MARK: - Unit assignment

    /// Pulls the assignment the supervisor wrote.
    ///
    /// What the station wrote always wins, unconditionally — this never overrides, edits
    /// or discards a stored record, not even one pointing at a unit the current
    /// environment does not hold. Tying a unit to a driver is the supervisor's act and
    /// this method never performs it, with the single scoped exception below.
    ///
    /// Without a stored record the driver has **no** unit: `unitAssignment` stays `nil`
    /// and the start screen says so. That is the correct operational state, and it is what
    /// every driver gets.
    func reloadAssignment() {
        let capability = unitAssignmentCapability
        if let adopted = UnitAssignmentRules.resolve(
            stored: AssignmentBook.assignment(driverId: driver.id),
            driverId: driver.id,
            capability: capability
        ) {
            unitAssignment = adopted
            return
        }
        // Seeding is a write into the shared book, so it is the boundary's business too:
        // a proved identity never fabricates its own assignment, not even the demo pair.
        guard capability.allowsLocalSimulation, let seeded = demoTitularUnit() else {
            unitAssignment = nil
            return
        }
        let assignment = AssignmentBook.make(
            stationId: driver.stationId,
            driverId: driver.id,
            driverName: driver.name,
            vehicleId: seeded.id,
            vehicleNumber: seeded.internalNumber,
            kind: .titular,
            note: "Asignación inicial del perfil de demostración.",
            assignedBy: "Supervisión de estación",
            origin: .simulated,
            now: now,
            previous: nil
        )
        AssignmentBook.upsert(assignment)
        unitAssignment = assignment
    }

    /// TEV-014 for Carlos Méndez Rivas, and for nobody else.
    ///
    /// One hardcoded pair, so the demonstration profile is navigable end to end without a
    /// supervisor session. This is **not** a general rule and must not become one: outside
    /// this exact driver and this exact unit, an unassigned driver stays unassigned, which
    /// is what the operational flow requires.
    ///
    /// The guards, in order: only the seeded demo driver — which is what confines this to
    /// one person in either environment — and only his titular unit, and only while that
    /// unit is still one of **his own** existing authorizations; the pair is checked
    /// against `authorizedVehicleIds`, never added to it.
    ///
    /// There is deliberately no environment guard. The demo credential now resolves to
    /// Carlos in test mode too, and a profile that opens without a unit there is precisely
    /// the failure this pairing exists to prevent. A laboratory driver is unaffected: he
    /// fails the identity guard on the first line.
    ///
    /// The remaining checks mirror the non-temporal blocking rules of
    /// `ShiftRules.validateUnit`: same station, free, operational, not held by another
    /// driver in the station's book. Seeding a unit that fails one of them would plant a
    /// permanent blocker on the start screen — worse than no unit. The temporal rule is
    /// deliberately excluded: the assignment exists at every hour, and the start window is
    /// judged when the driver actually tries to start.
    private func demoTitularUnit() -> Vehicle? {
        guard driver.id == MockData.seededDriver.id else { return nil }

        let unitId = MockData.seededTitularVehicleId
        guard driver.authorizedVehicleIds.contains(unitId) else { return nil }
        guard let vehicle = vehicles.first(where: { $0.id == unitId }) else { return nil }
        guard vehicle.stationId == driver.stationId else { return nil }
        guard vehicle.status == .available else { return nil }
        guard vehicle.occupiedBy == nil || vehicle.occupiedBy == driver.id else { return nil }
        // Not tied to another driver in the station's book.
        if let holder = AssignmentBook.holder(vehicleId: unitId), holder.driverId != driver.id {
            return nil
        }
        return vehicle
    }

    /// The unit the driver must take today: the substitute while it lasts, the titular one otherwise.
    var assignedVehicle: Vehicle? {
        guard let unitAssignment else { return nil }
        return vehicles.first { $0.id == unitAssignment.vehicleId }
    }

    var hasAssignedUnit: Bool { assignedVehicle != nil }

    /// Unit shown on the home screen: the one being driven, or the fixed one.
    var displayVehicle: Vehicle? { activeVehicle ?? assignedVehicle }

    // MARK: - Session scope

    var isAuthenticated: Bool { session != nil }

    /// Demonstration credential behind the session, when there is one.
    ///
    /// A Supabase session resolves to `nil` here on purpose: no `StaffAccount` is
    /// fabricated for it, because inventing a directory entry would put a password-bearing
    /// demo model back in the path of a real identity.
    var currentAccount: StaffAccount? { StaffDirectory.account(id: session?.accountId) }

    /// Identity proved by the backend for the open session, if it came from there.
    var currentPrincipal: SessionPrincipal? { session?.principal }

    /// The one test that separates a backend session from a demonstration one.
    var isBackendSession: Bool { session?.principal != nil }

    // MARK: - Execution environment

    /// The environment this session is running in, read live from the single source.
    ///
    /// Read, never stored. A capability that cached this would answer for whichever
    /// environment happened to be active when the session opened — which is precisely the
    /// failure 15B.13.2.1 fixes: entering the laboratory had to be done *before* signing
    /// in, because after signing in nothing asked again.
    var environment: LabMode { environmentSource.mode }

    /// Whether this session's records answer to a real station.
    ///
    /// Two conditions, and both are necessary. A proved identity is not enough on its own:
    /// inside the laboratory there is no station to contradict, the amber badge says so on
    /// every screen, and refusing to simulate there leaves a test account with an app it
    /// cannot exercise. And the laboratory is not enough on its own either: a demonstration
    /// credential simulates in both environments, as it always has.
    ///
    /// This is the single place the three boundaries below are decided from, so the
    /// environment cannot be honoured by one of them and ignored by another.
    var runsAgainstStation: Bool { isBackendSession && environment == .production }

    // MARK: - Financial boundary

    /// Whether this session may mint financial state locally.
    ///
    /// A demonstration session may: fabricating a contract or an income is the whole
    /// point of a flow that has no server behind it yet. A backend identity may not.
    /// Anything shown as money to a proved driver has to have come from the authority
    /// that owes it, and while there is no financial layer on the server the honest
    /// answer is that the operation is unavailable — not an invented contract that a
    /// settlement will happily subtract.
    ///
    /// This is the capability the writers ask. It lives here, not in the views: the
    /// session is the only thing that can answer it, and a screen that decided this for
    /// itself would be one refactor away from getting it wrong.
    var canSimulateFinancialState: Bool { !runsAgainstStation }

    /// Provenance every financial record this session produces is stamped with, and the
    /// one a settlement built from those records will accept.
    var ledgerOrigin: RecordOrigin { canSimulateFinancialState ? .simulated : .backend }

    // MARK: - Operational coordination boundary

    /// Whether this session may run the coverage workflow locally.
    ///
    /// Money was the first boundary; coordination is the second. An absence request, a
    /// claimed guard and a shift swap are decisions shared with a supervisor and a
    /// station, and this app writes them into one blob on one device. A demonstration
    /// session may do that: walking the chain end to end is the point. A proved identity
    /// may not, because no coverage service exists on the server yet, and a request that
    /// reaches nobody must never be shown as sent.
    ///
    /// Deliberately a second property instead of a reuse of the financial one. They
    /// answer alike today only because both backends are missing; coverage may well
    /// arrive before settlement, and when it does exactly one of them flips.
    var canSimulateOperationalCoordination: Bool { !runsAgainstStation }

    /// The capability the coverage board operates under for the open session.
    ///
    /// Asked here rather than decided in a view: the session is the only thing that can
    /// answer it, and a screen that judged this for itself would be one refactor away
    /// from getting it wrong.
    var coordinationCapability: CoordinationCapability {
        canSimulateOperationalCoordination ? .localWorkflow : .stationRequired
    }

    // MARK: - Unit assignment boundary

    /// Whether this session may create fleet inventory and unit assignments locally.
    ///
    /// The third boundary, and a third property rather than a reuse of the other two.
    /// A unit is not money and it is not a coverage request: it is a physical vehicle a
    /// supervisor hands to a person, and the station's system is the only authority that
    /// can say who holds which one. A demonstration session mints them freely, because a
    /// demonstration with no unit has nothing to demonstrate. A proved identity gets what
    /// the server assigned, which today is nothing — and "todavía no tienes unidad" is a
    /// true sentence, while a borrowed TEV-014 is not.
    var canSimulateUnitAssignment: Bool { !runsAgainstStation }

    /// The capability every read and write of the assignment book is judged against.
    var unitAssignmentCapability: UnitAssignmentCapability {
        canSimulateUnitAssignment ? .localSimulation : .stationRequired
    }

    // MARK: - Operational cycle boundary

    /// Whether this session may open, close and report the shift cycle locally.
    ///
    /// The fourth boundary, and a fourth property on purpose — the three above are not
    /// reused here even though all four read the same expression today. A unit assignment
    /// is a supervisor writing a row; a shift is the station certifying that a person
    /// drove for nine hours, and an incident is a report a human being has to receive.
    /// Those services arrive on different days: assignment is the one already being wired,
    /// and when it lands exactly one of these flips while the rest keep refusing.
    ///
    /// A demonstration or laboratory session runs the whole cycle, unchanged. A proved
    /// identity in production does not: there is nothing on the other end to register a
    /// start, so an `ActiveShift` minted here would be a nine-hour block the station never
    /// saw, feeding a history, a settlement and four bonuses.
    var canRunOperationalCycle: Bool { !runsAgainstStation }

    /// The capability the shift cycle and the incident report are judged against.
    var operationalCapability: OperationalCapability {
        canRunOperationalCycle ? .localWorkflow : .stationRequired
    }

    /// Provenance every operational record this session produces is stamped with, and the
    /// one restoration will accept back.
    var operationalOrigin: OperationalRecordOrigin { operationalCapability.origin }

    // MARK: - Notice boundary

    /// Whether this session may write into the driver's bell in the station's voice.
    ///
    /// The fifth boundary, and the smallest thing any of them guards — which is exactly
    /// why it needs its own. The four above stop records: a contract, a claimed guard, an
    /// assignment, a shift. A notice is not a record; it is a sentence addressed to the
    /// driver, and it is how every one of those records *announces itself*. "Depósito en
    /// efectivo notificado a gerencia" is not a row somebody might later read — it is the
    /// app telling a person, in the second person, that a manager has their receipt.
    ///
    /// It gets its own property rather than riding on the others because its future is
    /// the opposite of theirs. The others end when a service lands and the app starts
    /// writing real records. This one ends when the station starts *sending* — notices
    /// that correspond to no local record at all: a bay closed, a policy changed, a
    /// summons. That day this flips on its own, and the four below may still be refusing.
    var canPublishStationNotices: Bool { !runsAgainstStation }

    /// Whose voice the bell speaks in for the open session.
    var noticeAuthority: NoticeAuthority {
        canPublishStationNotices ? .localBulletin : .stationPublished
    }

    /// What the bell may show. Filtered by provenance, never emptied by deletion: a
    /// laboratory notice stays in the laboratory blob and returns with it.
    var visibleNotices: [Notice] {
        NoticeRules.visible(notices, authority: noticeAuthority)
    }

    /// Whether the shift standing in memory is one this session may act on.
    ///
    /// A `.simulated` shift left open inside the laboratory is not closeable from
    /// production: it is state of another operation that the container policy keeps, and
    /// closing it here would file a real `ShiftRecord` built out of a simulation.
    var canActOnActiveShift: Bool {
        guard let activeShift else { return false }
        return OperationalRecordRules.adopts(
            owner: activeShift.driverId,
            origin: activeShift.origin,
            driverId: driver.id,
            capability: operationalCapability
        )
    }

    var currentRole: StaffRole? { session?.role }

    var currentStation: Station? { StaffDirectory.station(id: session?.stationId) }

    /// Account allowed to unlock this device with Face ID, if any.
    var enrolledAccount: StaffAccount? { StaffDirectory.account(id: enrolledAccountId) }

    /// Interfaces are opened by role only: a driver can never render a supervisor screen.
    func hasAccess(to role: StaffRole) -> Bool { session?.role == role }

    /// The driver profile is exposed only inside a driver session.
    var driverProfile: Driver? {
        guard let account = currentAccount, account.role == .driver, account.driverId == driver.id else { return nil }
        return driver
    }

    // MARK: - Derived values

    /// Time the app obeys. It never comes from the phone: in production it is real time
    /// and in a simulation it is the logical time of the test environment, shared by every
    /// role and every device.
    ///
    /// **A pure read.** It answers what hour it is and registers no SwiftUI dependency.
    ///
    /// It used to read `ClockSignal.generation` first. That was load-bearing at the time and
    /// is deliberately gone now: one indiscriminate counter meant any adopted clock state
    /// invalidated every reader of `store.now` at once, across all seven roles — and worse,
    /// screens inherited temporal correctness by accident, through a side effect none of
    /// them named. Views that genuinely follow the clock now say so, one at a time, with
    /// `TimeScope` or `ClockAnchor`.
    ///
    /// Use this for **action time**: the instant a decision is taken, a form is preloaded, a
    /// snapshot is rebuilt or a seed key is computed. Never to make something on screen move
    /// by itself — nothing observes this any more, and nothing should.
    var now: Date {
        AppClock.now()
    }

    var activeVehicle: Vehicle? {
        guard let shift = activeShift else { return nil }
        return vehicles.first { $0.id == shift.vehicleId }
    }

    /// The badge on the bell. Counted over what may be shown, so a simulated notice can
    /// never leave a proved identity with an unread mark on an empty list.
    var unreadNoticeCount: Int { visibleNotices.filter { !$0.read }.count }

    var hasCredit: Bool { credit != nil }

    /// Transparent contract metrics for the credit panel.
    var creditMetrics: CreditMetrics? {
        guard let credit else { return nil }
        return CreditProgram.metrics(for: credit, now: now)
    }

    var goals: ShiftRules.Goals { ShiftRules.goals(for: driver.group) }

    func elapsedSeconds(at date: Date) -> Int {
        guard let shift = activeShift else { return 0 }
        return max(0, Int(date.timeIntervalSince(shift.startedAt)))
    }

    func estimatedKmDriven(at date: Date) -> Int {
        Int((Double(elapsedSeconds(at: date)) / 60 * Self.simulatedKmPerMinute).rounded())
    }

    var capturedPhotoCount: Int { activeShift?.photos.count ?? 0 }

    /// The start of shift only needs the odometer and the battery readings.
    var isInspectionComplete: Bool {
        guard let shift = activeShift else { return false }
        return InspectionSlot.driverSlots.allSatisfy { shift.photos[$0.rawValue] != nil }
    }

    /// Monday → Sunday late-minute log, the "bitácora" shown in Historial.
    struct LateDay: Identifiable, Sendable {
        let date: Date
        let label: String
        let minutes: Int
        let paidBackMinutes: Int
        let hasShift: Bool

        var id: Date { date }
        var pendingMinutes: Int { max(0, minutes - paidBackMinutes) }
    }

    func weeklyLateBreakdown(reference: Date) -> [LateDay] {
        let calendar = ShiftRules.calendar
        let start = ShiftRules.weekStart(for: reference)
        return (0..<7).compactMap { offset in
            guard let day = calendar.date(byAdding: .day, value: offset, to: start) else { return nil }
            let record = history.first { ShiftRules.isSameDay($0.startedAt, day) }
            return LateDay(
                date: day,
                label: Fmt.dayShort(day),
                minutes: record?.lateMinutes ?? 0,
                paidBackMinutes: record?.paidBackMinutes ?? 0,
                hasShift: record != nil
            )
        }
    }

    func weeklyLateDebt(reference: Date) -> Int {
        weeklyLateBreakdown(reference: reference).reduce(0) { $0 + $1.pendingMinutes }
    }

    func earnedToday(reference: Date) -> Int {
        let fromIncomes = incomes
            .filter { ShiftRules.isSameDay($0.date, reference) }
            .reduce(0) { $0 + $1.amountMxn }
        let fromClosedShifts = history
            .filter { ShiftRules.isSameDay($0.startedAt, reference) }
            .reduce(0) { $0 + $1.earningsMxn }
        return max(fromIncomes, fromClosedShifts, activeShift?.earningsMxn ?? 0)
    }

    func tripsToday(reference: Date) -> Int {
        let fromIncomes = incomes
            .filter { ShiftRules.isSameDay($0.date, reference) }
            .reduce(0) { $0 + $1.trips }
        return max(fromIncomes, activeShift?.trips ?? 0)
    }

    func earnedThisWeek(reference: Date) -> Int {
        incomes
            .filter { ShiftRules.isInSameWeek($0.date, as: reference) }
            .reduce(0) { $0 + $1.amountMxn }
    }

    struct DayEarnings: Identifiable, Sendable {
        let label: String
        let amount: Int
        let isToday: Bool
        let date: Date

        var id: Date { date }
    }

    func weeklyEarningsByDay(reference: Date) -> [DayEarnings] {
        let calendar = ShiftRules.calendar
        let start = ShiftRules.weekStart(for: reference)
        return (0..<7).compactMap { offset in
            guard let day = calendar.date(byAdding: .day, value: offset, to: start) else { return nil }
            let amount = incomes
                .filter { ShiftRules.isSameDay($0.date, day) }
                .reduce(0) { $0 + $1.amountMxn }
            return DayEarnings(
                label: Fmt.dayShort(day),
                amount: amount,
                isToday: ShiftRules.isSameDay(day, reference),
                date: day
            )
        }
    }

    // MARK: - Session

    /// Opens the session of an identity already proved by the backend.
    ///
    /// Deliberately a separate door from the demonstration one: it never consults
    /// `StaffDirectory`, never adds an account to it, and never resolves the driver
    /// through `MockData`. Everything the session shows about the person comes from the
    /// `principal` the server returned.
    ///
    /// The device is **not** enrolled for biometric unlock here. Repeating this sign-in
    /// without the password would require keeping a credential, which this phase does not
    /// do; Face ID keeps working exactly as before, for demonstration accounts only.
    ///
    /// Throws when a driver's membership is incomplete, before any state is touched.
    func signIn(principal: SessionPrincipal, method: SignInMethod) throws {
        // Built first: if the membership is incomplete this throws and the store is left
        // exactly as it was, with no half-open session.
        let profile: Driver? = principal.role == .driver
            ? try Self.sessionDriver(from: principal)
            : nil

        // Whatever is standing in memory belongs to the identity that is leaving. It is
        // written under **its own** key before anything is swapped, so opening a backend
        // session never costs the demonstration state a single record.
        persist()

        // The session opens in whatever environment the device is in, which is not
        // necessarily the one the last state was loaded from.
        adoptedEnvironment = environmentSource.mode

        // From here the store holds this identity's operational state and nothing else.
        adoptIdentityState(profileId: principal.profileId)

        if let profile {
            driver = profile
        }

        session = StaffSession(
            accountId: principal.profileId,
            role: principal.role,
            stationId: principal.stationId,
            method: method,
            startedAt: Date(),
            principal: principal
        )
        awaitsCredentialChoice = false
        reloadAssignment()
        persist()
    }

